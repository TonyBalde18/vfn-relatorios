-- Desempates por penáltis ficam com o resultado dos 90' (empate) e a nota em "jornada".
-- Pode ser corrido mais de uma vez: o índice único evita jogos repetidos.
-- =========================================================

CREATE TABLE IF NOT EXISTS h2h (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  data DATE NOT NULL,
  equipa_casa TEXT NOT NULL,
  equipa_fora TEXT NOT NULL,
  golos_casa INTEGER NOT NULL,
  golos_fora INTEGER NOT NULL,
  competicao TEXT NOT NULL,
  jornada TEXT,
  local TEXT CHECK (local IN ('casa', 'fora', 'neutro')) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS h2h_jogo_idx ON h2h (data, equipa_casa, equipa_fora);

-- RLS: só admin pode inserir/editar, todos podem ler
ALTER TABLE h2h ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "h2h_public_read" ON h2h;
DROP POLICY IF EXISTS "h2h_admin_write" ON h2h;
CREATE POLICY "h2h_public_read" ON h2h FOR SELECT USING (true);
CREATE POLICY "h2h_admin_write" ON h2h FOR ALL USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
) WITH CHECK (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);

