-- ---------------------------------------------------------
-- Jogos da época atual: quando um jogo do VFN (matches) fica "jogado" com resultado, entra
-- (ou é atualizado) na tabela h2h. O nome do adversário é teams.name (ou matches.opponent).
-- Os jogos entre outras equipas (home_team_id e away_team_id preenchidos) ficam de fora.
-- ---------------------------------------------------------
CREATE OR REPLACE FUNCTION public.vfn_h2h_do_jogo() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  adv text;
  em_casa boolean;
BEGIN
  IF lower(trim(coalesce(NEW.status, ''))) <> 'jogado' OR NEW.score_home IS NULL OR NEW.score_away IS NULL OR NEW.date IS NULL
     OR (NEW.home_team_id IS NOT NULL AND NEW.away_team_id IS NOT NULL) THEN
    RETURN NEW;
  END IF;
  SELECT t.name INTO adv FROM public.teams t WHERE t.id = NEW.opponent_team_id;
  adv := coalesce(adv, NEW.opponent);
  IF adv IS NULL OR adv = '' THEN RETURN NEW; END IF;
  em_casa := coalesce(NEW.home_away, '') ~* '^\s*(casa|home|c)\s*$';
  INSERT INTO public.h2h (data, equipa_casa, equipa_fora, golos_casa, golos_fora, competicao, jornada, local)
  VALUES ((NEW.date AT TIME ZONE 'Europe/Lisbon')::date,
          CASE WHEN em_casa THEN 'VF Naves' ELSE adv END,
          CASE WHEN em_casa THEN adv ELSE 'VF Naves' END,
          NEW.score_home, NEW.score_away, coalesce(NEW.competition, ''),
          CASE WHEN NEW.jornada IS NOT NULL THEN 'J' || NEW.jornada END,
          CASE WHEN em_casa THEN 'casa' ELSE 'fora' END)
  ON CONFLICT (data, equipa_casa, equipa_fora) DO UPDATE
    SET golos_casa = EXCLUDED.golos_casa, golos_fora = EXCLUDED.golos_fora,
        competicao = EXCLUDED.competicao, jornada = EXCLUDED.jornada;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS vfn_h2h_do_jogo ON public.matches;
CREATE TRIGGER vfn_h2h_do_jogo
  AFTER INSERT OR UPDATE OF status, score_home, score_away, date, opponent_team_id ON public.matches
  FOR EACH ROW EXECUTE FUNCTION public.vfn_h2h_do_jogo();

-- Os jogos desta época que já foram jogados (o trigger só apanha as alterações a partir de agora)
UPDATE public.matches SET status = status
WHERE lower(trim(coalesce(status, ''))) = 'jogado' AND score_home IS NOT NULL AND score_away IS NOT NULL
  AND NOT (home_team_id IS NOT NULL AND away_team_id IS NOT NULL);
